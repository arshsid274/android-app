    extraSmall = RoundedCornerShape(4.dp),
    small = RoundedCornerShape(8.dp),
    medium = RoundedCornerShape(8.dp),
    large = RoundedCornerShape(12.dp),
    extraLarge = RoundedCornerShape(16.dp),
)

@Composable
fun CueTheme(content: @Composable () -> Unit) {
    MaterialTheme(
        colorScheme = CueLightColors,
        typography = CueTypography,
        shapes = CueShapes,
        content = content,
    )
}

/** The ambient 32dp technical grid the designs draw behind onboarding surfaces. */
@Composable
fun GridPatternBackground(modifier: Modifier = Modifier) {
    val lineColor = Outline.copy(alpha = 0.05f)
    Canvas(modifier = modifier) {
        val step = 32.dp.toPx()
        var x = 0f
        while (x < size.width) {
            drawLine(lineColor, Offset(x, 0f), Offset(x, size.height), strokeWidth = 1f)
            x += step
        }
        var y = 0f
        while (y < size.height) {
            drawLine(lineColor, Offset(0f, y), Offset(size.width, y), strokeWidth = 1f)
            y += step
        }
    }
}
